"""Compose Figure 6 from its high-resolution base and new KE panel.

The base image is included in the versioned figure asset bundle. No existing
subplot is redrawn, rescaled or interpolated. Only panel b is replaced.
"""
from pathlib import Path
import argparse
import hashlib
import json


def sha256(path):
    digest = hashlib.sha256()
    with Path(path).open('rb') as handle:
        for block in iter(lambda: handle.read(4 * 1024 * 1024), b''):
            digest.update(block)
    return digest.hexdigest()


def compose(base_path, tile_path, output_dir, report_path=None):
    """Return output paths and the outside-panel pixel-preservation check."""
    import numpy as np
    from PIL import Image
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    box = (3220, 0, 6377, 1780)
    with Image.open(base_path) as image:
        original = image.convert('RGB')
    with Image.open(tile_path) as image:
        tile = image.convert('RGB')
    if original.size != (6377, 7157) or tile.size != (3157, 1780):
        raise ValueError('The base and panel must retain their original 900-dpi pixel dimensions.')
    result = original.copy()
    result.paste(tile, box[:2])
    png = output_dir / 'Figure_06.png'
    tiff = output_dir / 'Figure_06.tiff'
    if Path(base_path).resolve() in {png.resolve(), tiff.resolve()}:
        raise ValueError('Output must not overwrite the source base image.')
    result.save(png, dpi=(900, 900))
    result.save(tiff, compression='tiff_lzw', dpi=(900, 900))
    old, new = np.asarray(original), np.asarray(result)
    unchanged = (np.array_equal(old[:, :box[0]], new[:, :box[0]])
                 and np.array_equal(old[box[3]:], new[box[3]:]))
    if not unchanged:
        raise AssertionError('A pixel outside the replaced panel changed.')
    evidence = {'figure': 'Figure_06', 'replacement_box_pixels': list(box),
                'dimensions_pixels': list(original.size), 'dpi': 900,
                'base_sha256': sha256(base_path), 'tile_sha256': sha256(tile_path),
                'pixels_outside_panel_unchanged': unchanged,
                'outputs': [str(png), str(tiff)]}
    if report_path:
        report_path = Path(report_path)
        report_path.parent.mkdir(parents=True, exist_ok=True)
        report_path.write_text(json.dumps(evidence, indent=2), encoding='utf8')
    return evidence


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--base', type=Path, required=True,
                        help='Downloaded figure bundle: source_assets/Figure_06_before_vertical.png')
    parser.add_argument('--tile', type=Path, required=True,
                        help='Fig6b_new_tile.png generated by plot_mwt_integrals.py')
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    evidence = compose(args.base, args.tile, args.output, args.output / 'figure6_composition.json')
    print(json.dumps(evidence, indent=2))


if __name__ == '__main__':
    main()
